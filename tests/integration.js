(async () => {
  const results = [];
  const frame = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  const assert = (name, condition) => { results.push({ name, pass: !!condition }); };
  const apply = async settings => { await chrome.storage.local.set({ subtitleStudio: { ...SubtitleStudio.defaults, ...settings } }); await frame(); };
  await frame();
  document.querySelector('#video-container').dispatchEvent(new PointerEvent('pointerleave'));
  const root = document.querySelector('.shaka-text-container');
  let span = root.querySelector('span');
  assert('Default font overrides inherited inline size', getComputedStyle(span).fontSize === '32px');
  assert('Player UI is unaffected', getComputedStyle(document.querySelector('#player-control')).fontSize !== '32px');
  await apply({ fontSize: 46, color: '#ffe36e', italic: true, letterSpacing: 2, wordSpacing: 4, lineHeight: 1.5, offsetY: 70, maxWidth: 75, backgroundOpacity: 80, outlineWidth: 2 });
  let css = getComputedStyle(span);
  assert('Live updates override inline cue styles', css.fontSize === '46px' && css.color === 'rgb(255, 227, 110)' && css.fontStyle === 'italic');
  assert('Spacing applied to text', css.letterSpacing === '2px' && css.wordSpacing === '4px' && css.lineHeight === '69px');
  assert('Vertical offset applied to container', getComputedStyle(root).transform === 'matrix(1, 0, 0, 1, 0, -70)');
  assert('Background applied once to cue', getComputedStyle(root.firstElementChild).backgroundColor === 'rgba(0, 0, 0, 0.8)' && css.backgroundColor === 'rgba(0, 0, 0, 0)');
  const next = document.createElement('span'); next.textContent = 'A new cue'; next.style.color = 'red'; span.replaceWith(next); span = next; await frame();
  assert('New cues inherit saved styling', getComputedStyle(span).fontSize === '46px' && getComputedStyle(span).color === 'rgb(255, 227, 110)');
  await apply({ customCSS: 'text-transform: uppercase; font-size: 51px;' });
  assert('Custom declarations take precedence', getComputedStyle(span).textTransform === 'uppercase' && getComputedStyle(span).fontSize === '51px');
  assert('Reject CSS rule and URL injection', SubtitleStudio.customDeclarations('color:red;}body{display:none').error && SubtitleStudio.customDeclarations('background: url(https://example.com)').error);
  assert('Clamp malformed imported numeric values', SubtitleStudio.normalize({ fontSize: 9000, lineHeight: -5, color: 'invalid' }).fontSize === 120 && SubtitleStudio.normalize({ lineHeight: -5 }).lineHeight === .8);
  await apply({ enabled: false });
  assert('Disable restores original inline styling', getComputedStyle(span).fontSize === '28px' && getComputedStyle(span).color === 'rgb(255, 0, 0)' && getComputedStyle(root).transform === 'none');
  await apply({ fontSize: 37 });
  document.querySelector('#hotstar-subtitle-studio-style').remove(); await frame();
  assert('Stylesheet recovers after removal', getComputedStyle(span).fontSize === '37px');
  const replacement = root.cloneNode(true); root.replaceWith(replacement); await frame();
  assert('Replacement subtitle containers work without rescanning', getComputedStyle(replacement.querySelector('span')).fontSize === '37px');
  const caption = replacement.querySelector('span');
  const rect = caption.getBoundingClientRect();
  assert('Default placement remains inside video bounds', rect.top >= 0 && rect.bottom <= 540 && rect.left >= 0 && rect.right <= 960);
  caption.textContent = 'This is a longer subtitle that should wrap naturally inside the chosen maximum width without overflowing the video container.';
  await apply({ maxWidth: 40, textAlign: 'left' });
  assert('Long captions wrap within maximum width', caption.getBoundingClientRect().width <= 384 && caption.getBoundingClientRect().height > 42);
  await apply({ autoScale: true });
  assert('Auto size uses current player dimensions', getComputedStyle(caption).fontSize === '24px');
  const player = document.querySelector('#video-container');
  player.style.width = '640px'; player.style.height = '360px'; await frame();
  assert('Auto size follows player resize', getComputedStyle(caption).fontSize === '16px');
  player.style.width = '1280px'; player.style.height = '360px'; await frame();
  assert('Auto size accounts for letterboxing', getComputedStyle(caption).fontSize === '16px');
  player.style.width = '160px'; player.style.height = '90px'; await frame();
  assert('Auto size has a readable minimum', getComputedStyle(caption).fontSize === '12px');
  await apply({ autoScale: false, fontSize: 35 });
  assert('Fixed size remains independent of player dimensions', getComputedStyle(caption).fontSize === '35px');
  player.style.width = '960px'; player.style.height = '540px';
  assert('Auto size scales effects and offsets together', SubtitleStudio.scaled({ ...SubtitleStudio.defaults, autoScale: true, offsetY: 80, outlineWidth: 2 }, { width: 640, height: 360 }).offsetY === 40 && SubtitleStudio.scaled({ ...SubtitleStudio.defaults, autoScale: true, outlineWidth: 2 }, { width: 640, height: 360 }).outlineWidth === 1);
  await apply({ overlayControls: false });
  assert('Overlay controls can be disabled', !player.querySelector('[data-subtitle-studio-overlay]'));
  await apply({ overlayControls: true });
  const host = player.querySelector('[data-subtitle-studio-overlay]');
  assert('Overlay includes three accessible controls', host?.shadowRoot.querySelectorAll('button').length === 3);
  const media = player.querySelector('video');
  let position = 25;
  let paused = true;
  // A deterministic seekable media model; real media/PiP is checked separately.
  Object.defineProperties(media, {
    currentTime: { configurable: true, get: () => position, set: value => { position = value; } },
    paused: { configurable: true, get: () => paused },
    duration: { configurable: true, get: () => 60 },
    seekable: { configurable: true, get: () => ({ length: 2, start: i => i ? 40 : 0, end: i => i ? 60 : 30 }) }
  });
  media.play = async () => { paused = false; media.dispatchEvent(new Event('play')); };
  media.pause = () => { paused = true; media.dispatchEvent(new Event('pause')); };
  const buttons = host.shadowRoot.querySelectorAll('button');
  const nav = host.shadowRoot.querySelector('nav');
  player.dispatchEvent(new PointerEvent('pointerenter'));
  assert('Pointer entering the video reveals overlay', nav.hasAttribute('data-visible'));
  player.dispatchEvent(new PointerEvent('pointerleave'));
  media.pause();
  assert('Overlay stays hidden outside the video even when paused', !nav.hasAttribute('data-visible'));
  buttons[1].focus();
  assert('Focus cannot keep overlay visible after pointer leaves', !nav.hasAttribute('data-visible'));
  player.dispatchEvent(new PointerEvent('pointerenter'));
  window.dispatchEvent(new Event('blur'));
  assert('Leaving the window hides overlay', !nav.hasAttribute('data-visible'));
  player.dispatchEvent(new PointerEvent('pointermove'));
  assert('Returning the pointer reveals overlay again', nav.hasAttribute('data-visible'));
  let bubbled = false;
  const onClick = () => { bubbled = true; };
  player.addEventListener('click', onClick);
  buttons[0].click(); assert('Rewind overlay seeks ten seconds', position === 15);
  buttons[2].click(); assert('Forward overlay seeks ten seconds', position === 25);
  buttons[1].click(); await frame();
  assert('Overlay plays and updates its accessible label', !paused && buttons[1].ariaLabel === 'Pause video');
  buttons[1].click();
  assert('Overlay pauses and prevents host click-to-pause conflicts', paused && buttons[1].ariaLabel === 'Play video' && !bubbled);
  player.removeEventListener('click', onClick);
  position = 55; buttons[2].click();
  assert('Seeking clamps to the stream endpoint', position === 60);
  position = 3; buttons[0].click();
  assert('Seeking clamps to the stream start', position === 0);
  position = 25; buttons[2].click();
  assert('Seeking snaps across gaps to a valid range', position === 30);
  const scrubber = host.shadowRoot.querySelector('input[type=range]');
  media.dispatchEvent(new Event('timeupdate'));
  assert('Seek bar follows playback and displays remaining time', Number(scrubber.value) === 30 && host.shadowRoot.querySelector('.time').textContent === '0:30');
  scrubber.value = '45'; scrubber.dispatchEvent(new Event('input'));
  assert('Dragging seek bar changes playback position', position === 45);
  scrubber.value = '35'; scrubber.dispatchEvent(new Event('input'));
  assert('Seek bar also clamps targets inside stream gaps', position === 30);
  position = 55; media.dispatchEvent(new Event('timeupdate'));
  assert('Seek bar exposes elapsed time accessibly', scrubber.getAttribute('aria-valuetext') === '0:55 of 1:00');
  Object.defineProperty(media, 'seekable', { configurable: true, get: () => ({ length: 0 }) });
  media.dispatchEvent(new Event('progress'));
  assert('Seek bar is disabled for streams without seeking', scrubber.disabled);
  await apply({ overlayControls: false });
  assert('Removing overlay leaves no UI behind', !host.isConnected);
  window.testResults = results;
  document.querySelector('#results').textContent = JSON.stringify(results, null, 2);
})();
